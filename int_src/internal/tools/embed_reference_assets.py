#!/usr/bin/env python3
"""Generate the embedded UI resources, preserving all original RGBA pixels.

Regeneration requires Pillow. The generated C++ header has no image-decoder
dependency: Android's zlib expands the verified RGBA byte arrays at startup.
"""
from pathlib import Path
import hashlib
import json
import zlib
from PIL import Image

root = Path(__file__).resolve().parents[1] / "jni"
assets = root / "reference_assets"
manifest = json.loads((assets / "manifest.json").read_text())
for item in manifest["resources"]:
    if hashlib.sha256((assets / item["file"]).read_bytes()).hexdigest() != item["sha256"]:
        raise ValueError(f"Resource checksum mismatch: {item['file']}")

images = [("Avatar", "image-16c418.png"), ("Home", "image-1aa4a0.png"),
          ("Aim", "image-1ac828.png"), ("Visuals", "image-1b1828.png"),
          ("Memory", "image-1b3f40.png"), ("Other", "image-1b6868.png"),
          ("Settings", "image-1b7fe8.png")]
with (root / "reference_assets_data.h").open("w") as out:
    out.write("// Generated by tools/embed_reference_assets.py; do not edit.\n")
    out.write("#pragma once\n#include <cstddef>\nnamespace mango_reference {\n")
    def array(name, data):
        out.write(f"inline constexpr unsigned char {name}[] = {{\n")
        for i in range(0, len(data), 24):
            out.write("    " + ",".join(f"0x{x:02x}" for x in data[i:i+24]) + ",\n")
        out.write("};\n")
    array("font_vector", (assets / "font-44ff9.ttf").read_bytes())
    array("font_pixel", (assets / "font-42a8a.ttf").read_bytes())
    dimensions = []
    for name, filename in images:
        im = Image.open(assets / filename).convert("RGBA")
        array("image_" + name, zlib.compress(im.tobytes(), 9))
        dimensions.append(im.size)
    out.write("enum Asset {" + ",".join(n for n, _ in images) + ",AssetCount};\n")
    out.write("struct ImageData {const unsigned char* data;std::size_t size;int width,height;};\n")
    out.write("inline constexpr ImageData images[AssetCount] = {\n")
    for (name, _), (width, height) in zip(images, dimensions):
        out.write(f"    {{image_{name},sizeof(image_{name}),{width},{height}}},\n")
    out.write("};\n}\n")
print("Embedded two fonts and seven images without resizing")
labels=json.loads((assets / "labels.json").read_text())
with (root / "reference_labels.h").open("w") as out:
    out.write('// Generated from the reference label tables.\n#pragma once\n#include <cstring>\nnamespace mango_reference {\n')
    out.write('inline const char* translate(const char* text,bool russian) {\n')
    out.write('    if(!russian)return text;\n    static const char* labels[][2]={\n')
    for english,russian in labels:
        out.write('        {'+json.dumps(english,ensure_ascii=False)+','+json.dumps(russian,ensure_ascii=False)+'},\n')
    out.write('    };\n    for(const auto& pair:labels)if(!std::strcmp(text,pair[0]))return pair[1];\n    return text;\n}\n}\n')
palette=json.loads((assets / "palette.json").read_text())
with (root / "reference_palette.h").open("w") as out:
    out.write('#pragma once\n#include "imgui.h"\nnamespace mango_reference {\n')
    out.write('// Original float32 palette at reference RVA 0x1aa20, all 28 RGBA values.\n')
    out.write('inline constexpr ImVec4 palette[]={\n')
    for color in palette:
        out.write('    {'+','.join(format(v,'.9g')+('.f' if v==int(v) else 'f') for v in color)+'},\n')
    out.write('};\n}\n')
